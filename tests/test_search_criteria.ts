import assert from 'node:assert/strict';
import { evaluateSearchCriteria as evaluate } from '../src/services/searchCriteria';
assert.equal(evaluate({ workload: '100%' }, { workload: '' }).excluded, false);
assert.equal(evaluate({ workload: '100%' }, { workload: '100' }).excluded, false);
assert.equal(evaluate({ workload: '100%' }, { workload: '90' }).excluded, true);
assert.equal(evaluate({ workload: '80–100%' }, { workload: '90' }).excluded, false);
assert.equal(evaluate({}, { workload: '90' }).excluded, false);
assert.equal(evaluate({ workload: '0–90%' }, { workload: '90' }).excluded, false);
assert.equal(evaluate({ salary: null }, { salary_min: '130000' }).excluded, false);
assert.equal(evaluate({ salary: 'CHF 120000' }, { salary_min: '130000' }).excluded, true);
assert.equal(evaluate({ salary: 'CHF 120000–140000' }, { salary_min: '130000' }).excluded, false);
assert.equal(evaluate({ salary: 'CHF 90000' }, { salary_min: '' }).excluded, false);
assert.equal(evaluate({ salary: 'EUR 90000' }, { salary_min: '130000' }).excluded, false);
